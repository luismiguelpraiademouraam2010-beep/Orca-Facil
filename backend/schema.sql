CREATE DATABASE IF NOT EXISTS orcafacil CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE orcafacil;

CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 empresa VARCHAR(160) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NOT NULL,
 criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS clientes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id BIGINT UNSIGNED NOT NULL,
 nome VARCHAR(160) NOT NULL,
 email VARCHAR(190) NOT NULL,
 telefone VARCHAR(30),
 empresa VARCHAR(160),
 criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS servicos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id BIGINT UNSIGNED NOT NULL,
 nome VARCHAR(160) NOT NULL,
 categoria VARCHAR(100),
 descricao TEXT,
 preco DECIMAL(12,2) NOT NULL DEFAULT 0,
 criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS orcamentos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id BIGINT UNSIGNED NOT NULL,
 cliente VARCHAR(160) NOT NULL,
 descricao TEXT,
 data DATE NOT NULL,
 validade DATE NULL,
 status ENUM('Pendente','Aprovado','Rejeitado') NOT NULL DEFAULT 'Pendente',
 total DECIMAL(12,2) NOT NULL DEFAULT 0,
 criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS empresas (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario_id BIGINT UNSIGNED NOT NULL UNIQUE,
 nome VARCHAR(160), cnpj VARCHAR(20), email VARCHAR(190),
 telefone VARCHAR(30), endereco VARCHAR(255), descricao TEXT,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;
